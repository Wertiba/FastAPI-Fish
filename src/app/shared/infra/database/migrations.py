"""Migrations written in plain SQL: an Alembic revision that only runs ``<revision>.up.sql`` / ``.down.sql``.

``make migration-sql m="add projects"`` creates the trio::

    0003_add_projects.py         revision chain (ids, down_revision) -- nothing to edit
    0003_add_projects.up.sql     the DDL: written by hand or exported (pgAdmin -> Schema Diff)
    0003_add_projects.down.sql   how to undo it

Alembic still numbers, orders and records revisions, so ``alembic upgrade head`` and the ``api``
startup migration work as before, and SQL revisions mix with autogenerated ones.
"""

from pathlib import Path
from typing import Literal

from sqlalchemy.util import await_only

from alembic import context, op


def sql_path(revision_file: str, direction: Literal["up", "down"]) -> Path:
    revision = Path(revision_file)
    return revision.with_name(f"{revision.stem}.{direction}.sql")


def has_statements(script: str) -> bool:
    return any(line.strip() and not line.strip().startswith("--") for line in script.splitlines())


def run_sql(revision_file: str, direction: Literal["up", "down"]) -> None:
    """Runs the whole file in the migration's transaction; several statements and ``$$`` bodies are fine."""
    script = sql_path(revision_file, direction).read_text(encoding="utf-8")
    if not has_statements(script):
        return
    if context.is_offline_mode():  # ``alembic upgrade --sql``: the script goes to the output as is
        op.execute(script)
        return
    connection = op.get_bind()
    if connection.dialect.driver == "asyncpg":
        # asyncpg prepares every statement it gets through SQLAlchemy, and a prepared statement holds
        # one command. Its own ``execute`` without arguments uses the simple protocol, which runs a
        # script. ``SELECT 1`` makes sure SQLAlchemy has opened the transaction the script joins.
        connection.exec_driver_sql("SELECT 1")
        await_only(connection.connection.driver_connection.execute(script))  # type: ignore[union-attr]
    else:
        connection.exec_driver_sql(script)
